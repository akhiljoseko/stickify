/// Identifier keys representing the key feature areas/modules of the application.
enum FeatureId {
  /// The main telemetry summary dashboard.
  dashboard,

  /// The interactive sheet layout slot selector print setup page.
  printSetup,

  /// The search list index page.
  search,

  /// The multi-step template configuration wizard (Sheet Config, Sticker Setup, Label Editor, Preview).
  templateCreation,

  /// The catalogue product administration editor CRUD screens.
  productCatalogAdmin,

  /// The general catalogue product list browsing and detail drawer screens.
  productCatalogView,

  /// The product packaging variant detail price editing screen.
  productVariantEdit,
}
